async function load(lockName: string, lock: string): Promise<Project> {
  const { root, cleanup } = await makeWorkspace({ 'package.json': MANIFEST, [lockName]: lock });
  try {
    const project = await loadProject(root, root);
    if (!project) throw new Error('project not loaded');
    return project;
  } finally {
    await cleanup();
  }
}

function locations(lock: LockfileSummary | undefined): Record<string, string> {
  return Object.fromEntries(
    (lock?.packages ?? []).map((pkg) => [pkg.location, `${pkg.version}${pkg.dev ? ' dev' : ''}`]),
  );
}

const HOISTED = {
  'node_modules/@types/react': '17.0.80 dev',
  'node_modules/js-tokens': '4.0.0',
  'node_modules/legacy-tool': '1.2.0 dev',
  'node_modules/legacy-tool/node_modules/js-tokens': '3.0.2 dev',
  'node_modules/loose-envify': '1.4.0',
  'node_modules/object-assign': '4.1.1',
  'node_modules/react': '17.0.2',
};

describe.each([
  ['yarn classic', 'yarn.lock', YARN_CLASSIC, 'yarn', 1],
  ['yarn berry', 'yarn.lock', YARN_BERRY, 'yarn', undefined],
  ['pnpm v5', 'pnpm-lock.yaml', PNPM_V5, 'pnpm', 5.4],
  ['pnpm v9', 'pnpm-lock.yaml', PNPM_V9, 'pnpm', 9],
] as const)('%s lockfile', (_label, lockName, lock, kind, version) => {
  it('hoists like npm, nests conflicts under their owner and marks dev-only packages', async () => {
    const project = await load(lockName, lock);
    expect(project.lockfile?.kind).toBe(kind);
    expect(project.lockfile?.version).toBe(version);
    expect(locations(project.lockfile)).toEqual(HOISTED);
    expect(project.lockfile?.rootSpecs).toEqual({
      react: '^17.0.2',
      'legacy-tool': '^1.0.0',
      '@types/react': '^17.0.0',
    });
  });

  it('feeds version resolution and dependency edges', async () => {
    const project = await load(lockName, lock);
    expect(resolveVersion(project, 'react')).toEqual({
      version: '17.0.2',
      source: 'lockfile',
      spec: '^17.0.2',
    });
    expect(resolveVersion(project, '@types/react')?.version).toBe('17.0.80');
    const react = project.lockfile?.packages.find((pkg) => pkg.name === 'react');
    expect(react && isTopLevel(react)).toBe(true);
    expect(react?.requires).toEqual(['loose-envify', 'object-assign']);
  });
});

describe('pnpm metadata', () => {
  it('reads engines, deprecations and peers', async () => {
    const project = await load('pnpm-lock.yaml', PNPM_V9);
    const byName = (name: string, version: string) =>
      project.lockfile?.packages.find((pkg) => pkg.name === name && pkg.version === version);
    expect(byName('react', '17.0.2')?.engines).toEqual({ node: '>=0.10.0' });
    expect(byName('js-tokens', '3.0.2')?.deprecated).toBe('use js-tokens 4');
    expect(byName('legacy-tool', '1.2.0')?.peerDependencies).toEqual({ react: '>=16' });
  });
});

describe('lockfile drift for yarn and pnpm', () => {
  async function driftOf(
    lockName: string,
    lock: string,
    dependencies: Record<string, string> = { react: '^18.2.0' },
  ): Promise<string[] | undefined> {
    const manifest = { ...MANIFEST, dependencies };
    const { root, cleanup } = await makeWorkspace({ 'package.json': manifest, [lockName]: lock });
    try {
      const config = configSchema.parse({});
      const report = await analyze(await discoverWorkspace(root, { config }), {
        config,
        offline: true,
        today: TODAY,
        installedNodes: fakeNodes('22.19.0'),
      });
      return report.projects[0]?.findings.find((finding) => finding.ruleId === 'npm/lockfile-drift')
        ?.evidence;
    } finally {
      await cleanup();
    }
  }

  it('reports a spec yarn has no descriptor for', async () => {
    expect(await driftOf('yarn.lock', YARN_CLASSIC)).toEqual(['react: missing from lockfile']);
    expect(await driftOf('yarn.lock', YARN_BERRY)).toEqual(['react: missing from lockfile']);
  });

  it('reports a changed yarn spec even when a transitive copy satisfies it', async () => {
    // react-dom hoists react@17.0.2, but yarn has no descriptor for react@^17.0.0 and re-resolves it.
    const lock = `${YARN_CLASSIC}
react-dom@^17.0.2:
  version "17.0.2"
  dependencies:
    react "^17.0.2"
`;
    expect(await driftOf('yarn.lock', lock, { react: '^17.0.0', 'react-dom': '^17.0.2' })).toEqual([
      'react: missing from lockfile',
    ]);
  });

  it('accepts an in-sync yarn lockfile with local specs', async () => {
    const dependencies = { react: '^17.0.2', lib: 'file:../lib' };
    expect(await driftOf('yarn.lock', YARN_CLASSIC, dependencies)).toBeUndefined();
    expect(await driftOf('yarn.lock', YARN_BERRY, dependencies)).toBeUndefined();
  });

  it('reports a spec that differs from the pnpm specifier', async () => {
    expect(await driftOf('pnpm-lock.yaml', PNPM_V9)).toEqual([
      'react: package.json ^18.2.0, lockfile ^17.0.2',
    ]);
  });
});
